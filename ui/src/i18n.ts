function pluralRu(n: number, one: string, few: string, many: string) {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}

export interface I18n {
  lang: Language;
  locale: string;
  t: (k: Key) => string;
  status: (s: Status) => string;
  kind: (k: Kind) => string;
  finding: (f: Finding) => string;
  level: (l: Level) => string;
  torrents: (n: number) => string;
  peersCount: (n: number) => string;
  seedsCount: (n: number) => string;
}

export function makeI18n(lang: Language): I18n {
  const d = dicts[lang];
  const isRu = lang === "ru";
  return {
    lang,
    locale: isRu ? "ru-RU" : "en-US",
    t: (k) => d[k],
    status: (s) => (isRu ? statusRu : statusEn)[s],
    kind: (k) => (isRu ? kindRu : kindEn)[k],
    finding: (f) => (isRu ? findingRu : findingEn)[f],
    level: (l) => (isRu ? levelRu : levelEn)[l],
    torrents: (n) =>
      isRu ? `${n} ${pluralRu(n, "торрент", "торрента", "торрентов")}` : `${n} ${n === 1 ? "torrent" : "torrents"}`,
    peersCount: (n) =>
      isRu ? `${n} ${pluralRu(n, "пир", "пира", "пиров")}` : `${n} ${n === 1 ? "peer" : "peers"}`,
    seedsCount: (n) =>
      isRu ? `${n} ${pluralRu(n, "сид", "сида", "сидов")}` : `${n} ${n === 1 ? "seed" : "seeds"}`,
  };
}

export const I18nContext = createContext<I18n>(makeI18n("ru"));
export const useI18n = () => useContext(I18nContext);
